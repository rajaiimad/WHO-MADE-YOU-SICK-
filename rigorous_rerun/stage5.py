"""
rigorous_rerun.stage5
=====================
Stage 5 (PREREGISTRATION_v6.md): stronger adaptive attackers. Run with XRP_GEN=v2.

Detectors are trained once per seed on the v2 main corpus (unsafe label) and never retrained.
Test corpora (seeds 70000-70059):
  standard, oov_audio      generated by stage3.generate (oov hook moves the attacker out of view)
  switching, split, blackbox  channel-only changes applied to the standard corpus; scores and
                           labels are updated exactly by the change in each modified edge's
                           contribution, under the same noise draw.
"""
from __future__ import annotations

import time

import numpy as np
from scipy.stats import norm
from sklearn.metrics import average_precision_score

from common import CACHE, OUT, PEER_HI, PEER_NAMES, SEED_RANGES, SEEDS, jdump, thresholds_from_val
from coper_vr.config import PEER_CHANNELS
from coper_vr.data.gen_param import GenParams, _attacker_profile
from stage3 import S3, V2_GAIN, W, generate

OD = OUT / "stage5"
SEED0, NC = 70_000, 60
for r in list(SEED_RANGES.values()) + list(S3.values()):
    assert SEED0 + NC <= r[0] or SEED0 >= r[1], "stage-5 seeds overlap"
MODELS = ["rule__RULE", "proto__MLPpub", "edgefeat__HGB", "gat__GAT", "mpnn__MPNN"]
N, T, TRACKS = 4, 48, 8
BLO = np.array([c.benign_lo for c in PEER_CHANNELS], np.float32)
BHI = np.array([c.benign_hi for c in PEER_CHANNELS], np.float32)
PROFILES = ["ramp", "constant", "pulse", "burst", "intermittent"]


# ---------------------------------------------------------------- corpora
def base(name, v):
    f = CACHE / f"s5_{name}.npz"
    if f.exists():
        z = np.load(f)
        return {k: z[k] for k in z.files}
    t = generate(SEED0, NC, v, V2_GAIN)
    np.savez_compressed(f, **t)
    return t


def contrib(pc, geo):
    """Contribution at gain 1 of peer channels pc (T,5) over an edge with geometry geo (T,3)."""
    dd = geo[:, 0].astype(np.float64) + 1e-3
    ov = geo[:, 1].astype(np.float64)
    nrm = pc / PEER_HI
    return np.where(ov == 0, W[4] * nrm[:, 4] / dd, (nrm @ W) * ov / dd)


def track_rows(k):
    """Rows of track k (cohort-major, then track): row(i, t) = start + i*T + t."""
    return k * N * T


def attacker_pc(t, k):
    s = track_rows(k)
    aid = int(t["atk_id"][s])
    i = (aid + 1) % N
    slot = int(np.where(t["E_src"][s + i * T] == aid)[0][0])
    return aid, t["E_chan"][s + i * T:s + (i + 1) * T, slot].astype(np.float64)


def apply(t, mods):
    """mods: {track: {peer: new PC (T,5)}}. Returns a new corpus with exact label updates; the
    attacker-induced label and harm use all modified peers of a track as colluders."""
    o = {k: v.copy() for k, v in t.items()}
    G = V2_GAIN
    o["colluder"] = np.zeros(len(t["y"]), bool)
    for key in ("atk_term", "s_noisy", "oracle_score"):
        o[key] = t[key].astype(np.float64)
    for k, peers in mods.items():
        s0 = track_rows(k)
        for i in range(N):
            rs = slice(s0 + i * T, s0 + (i + 1) * T)
            if i in peers:
                o["colluder"][rs] = True
            new_term = np.zeros(T)
            for slot, j in enumerate(t["E_src"][s0 + i * T]):
                if int(j) not in peers:
                    continue
                geo = t["E_geo"][rs, slot]
                d = G * (contrib(peers[int(j)], geo) - contrib(t["E_chan"][rs, slot].astype(np.float64), geo))
                o["E_chan"][rs, slot] = peers[int(j)]
                o["s_noisy"][rs] += d
                o["oracle_score"][rs] += d
                new_term += G * contrib(peers[int(j)], geo)
            o["atk_term"][rs] = 0.0 if i in peers else new_term
    sv = o["s_noisy"]
    o["sev"] = (sv > 0.15).astype(np.int64) + (sv > 0.30) + (sv > 0.55)
    o["y"] = (sv > 0.30).astype(np.int64)
    return o


def labels(t):
    """Attacker-induced label and expected harm (Stage-4 definition)."""
    a = t["atk_term"]
    victim = (t["atk_id"] >= 0) & (np.arange(len(a)) // T % N != t["atk_id"]) & ~t.get("colluder", np.zeros(len(a), bool))
    y_ai = ((t["s_noisy"] > 0.30) & (t["s_noisy"] - a <= 0.30) & victim).astype(np.int64)
    sc = t["oracle_score"]
    p_ai = np.where(victim, norm.cdf((0.30 - sc + a) / 0.05) - norm.cdf((0.30 - sc) / 0.05), 0.0)
    return y_ai, p_ai


def profile(rng, ch, scale=1.0, prof="ramp"):
    return _attacker_profile(rng, T, ch, GenParams(temporal_profile=prof, intensity_scale=scale)).astype(np.float64)


def benign(rng, k):
    return rng.uniform(BLO[k], BHI[k], T)


def attacked_tracks(t):
    return [k for k in range(NC * TRACKS) if t["atk_id"][track_rows(k)] >= 0]


def switching(t):
    mods = {}
    for k in attacked_tracks(t):
        rng = np.random.default_rng([SEED0, k, 1])
        aid, pc = attacker_pc(t, k)
        ach = int(t["atk_ch"][track_rows(k)]) - 1
        pc = pc.copy()
        pc[:, ach] = benign(rng, ach)
        prof = {c: profile(rng, PEER_NAMES[c]) for c in range(5)}
        order = rng.permutation(5)
        for seg, st in enumerate(range(0, T, 8)):
            c = order[seg % 5]
            pc[st:st + 8, c] = prof[c][st:st + 8]
        mods[k] = {aid: pc}
    return apply(t, mods)


def split(t):
    mods = {}
    for k in attacked_tracks(t):
        rng = np.random.default_rng([SEED0, k, 2])
        aid, pc = attacker_pc(t, k)
        ach = int(t["atk_ch"][track_rows(k)]) - 1
        j2 = int(rng.choice([u for u in range(N) if u != aid]))
        i = next(u for u in range(N) if u not in (aid, j2))
        s0 = track_rows(k)
        slot = int(np.where(t["E_src"][s0 + i * T] == j2)[0][0])
        pc2 = t["E_chan"][s0 + i * T:s0 + (i + 1) * T, slot].astype(np.float64).copy()
        half = lambda y: BHI[ach] + 0.5 * (y - BHI[ach])
        pc = pc.copy()
        pc[:, ach] = half(pc[:, ach])
        pc2[:, ach] = half(profile(rng, PEER_NAMES[ach]))
        mods[k] = {aid: pc, j2: pc2}
    return apply(t, mods)


def blackbox(t, score_fn, thr, n_cand=24):
    """score_fn(corpus-like dict of rows) -> surrogate probabilities."""
    from run_detection import SPECS
    feat = SPECS["mpnn__MPNN"][1]
    mods, log = {}, []
    _, p_std = labels(t)
    for k in attacked_tracks(t):
        rng = np.random.default_rng([SEED0, k, 3])
        aid, pc0 = attacker_pc(t, k)
        ach = int(t["atk_ch"][track_rows(k)]) - 1
        cands = [pc0]
        for _ in range(n_cand):
            c = int(rng.integers(0, 5)); a = float(rng.uniform(0.3, 1.0)); pr = PROFILES[int(rng.integers(0, 5))]
            pc = pc0.copy()
            pc[:, ach] = benign(rng, ach)
            pc[:, c] = profile(rng, PEER_NAMES[c], a, pr)
            cands.append(pc)
        s0 = track_rows(k)
        rows = np.arange(s0, s0 + N * T)
        sub = {kk: v[rows] for kk, v in t.items() if isinstance(v, np.ndarray) and v.ndim and len(v) == len(t["y"])}
        sub["atk_id"] = t["atk_id"][rows]
        h_std = p_std[rows].sum()
        best = None
        for ci, pc in enumerate(cands):
            m = apply(dict(sub), {0: {aid: pc}})
            _, p_ai = labels(m)
            harm = p_ai.sum()
            _, V, E = feat(m)
            p = score_fn(V, E)
            vic = np.arange(len(rows)) // T != aid
            alarms = int((p[vic] >= thr).sum())
            key = (alarms, float(p[vic].mean()))
            if harm >= 0.5 * h_std and (best is None or key < best[0]):
                best = (key, ci, pc, harm)
        mods[k] = {aid: best[2]}
        log.append({"track": k, "chosen": best[1], "alarms": best[0][0], "harm": float(best[3]), "harm_std": float(h_std)})
    return apply(t, mods), log


# ---------------------------------------------------------------- detectors
def mpnn_scorer(meta, cfg):
    from models import _logd, _predict, _torch
    torch = _torch()
    net, (sv, se) = meta["net"], meta["scalers"]
    devc = next(net.parameters()).device

    def f(V, E):
        Vt = torch.tensor(sv(V), device=devc)
        Et = torch.tensor(se(_logd(E, cfg["logd"])), device=devc)
        return _predict(net, lambda s: net(Vt[s], Et[s]), len(Vt))
    return f


def train(name, dev, tests):
    import baselines  # noqa: F401
    from models import FAMILIES
    from run_detection import SPECS, fixed_cfg
    from run_final import train_val_split
    fam = name.split("__")[1]
    builder = SPECS[name][1]
    cfg = {} if fam in ("MLPpub", "RULE") else fixed_cfg(fam, name)
    cfg.pop("n_iter", None)
    kd = builder(dev)
    kts = {c: builder(t) for c, t in tests.items()}
    y = dev["y"]
    out = []
    for s in SEEDS:
        tr, va = train_val_split(dev["ctx"], y, s)
        if kd[0] == "tab":
            d = {"Xtr": kd[1][tr], "ytr": y[tr], "Xva": kd[1][va], "yva": y[va], "Xte": {c: k[1] for c, k in kts.items()}}
        else:
            d = {"Vtr": kd[1][tr], "Etr": kd[2][tr], "ytr": y[tr], "Vva": kd[1][va], "Eva": kd[2][va], "yva": y[va],
                 "Gte": {c: (k[1], k[2]) for c, k in kts.items()}}
        pv, pt = FAMILIES[fam](d, cfg, s)
        out.append({"seed": s, "thr": thresholds_from_val(y[va], pv), "pred": pt,
                    "scorer": mpnn_scorer(d["_meta"], cfg) if fam == "MPNN" else None})
    return out


def evaluate(t, p, thr):
    y_ai, _ = labels(t)
    neg = t["y"] == 0
    r = {"pr_attacker": float(average_precision_score(y_ai, p)), "pr_unsafe": float(average_precision_score(t["y"], p))}
    for b in ("fpr10", "fpr1"):
        yh = p >= thr[b]
        r[f"recall_attacker_{b}"] = float(yh[y_ai == 1].mean())
        r[f"realised_fpr_{b}"] = float(yh[neg].mean())
    return r


def main():
    t0 = time.time()
    OD.mkdir(parents=True, exist_ok=True)
    dev = np.load(CACHE / "s4_main.npz")
    dev = {k: dev[k] for k in dev.files}
    std = base("standard", {})
    # checks: the contribution formula reproduces the generator's attacker term, and an
    # identity modification leaves every label unchanged
    ks = attacked_tracks(std)
    for k in ks[:20]:
        aid, pc = attacker_pc(std, k)
        i = (aid + 1) % N
        rs = slice(track_rows(k) + i * T, track_rows(k) + (i + 1) * T)
        slot = int(np.where(std["E_src"][rs.start] == aid)[0][0])
        assert np.allclose(V2_GAIN * contrib(pc, std["E_geo"][rs, slot]), std["atk_term"][rs], atol=1e-4)
    same = apply(std, {k: {attacker_pc(std, k)[0]: attacker_pc(std, k)[1]} for k in ks})
    assert np.array_equal(same["y"], std["y"]) and np.array_equal(labels(same)[0], labels(std)[0])
    tests = {"standard": std, "oov_audio": base("oov_audio", {"oov": True}),
             "oov_audio_d1": base("oov_audio_d1", {"oov": True, "oov_min_d": 1.0}),   # amendment, see PREREGISTRATION_v6
             "switching": switching(std), "split": split(std)}
    print(f"corpora ready ({time.time() - t0:.0f}s)", flush=True)
    res = {"harm": {}, "models": {}}
    mp = train("mpnn__MPNN", dev, tests)
    print(f"mpnn trained ({time.time() - t0:.0f}s)", flush=True)
    bb, log = blackbox(std, mp[0]["scorer"], mp[0]["thr"]["fpr10"])
    tests["blackbox"] = bb
    res["blackbox_log"] = log
    from run_detection import SPECS
    _, V, E = SPECS["mpnn__MPNN"][1](bb)
    for r in mp:
        r["pred"]["blackbox"] = r["scorer"](V, E)
    print(f"blackbox built ({time.time() - t0:.0f}s)", flush=True)
    for c, t in tests.items():
        y_ai, p_ai = labels(t)
        res["harm"][c] = {"attacker_induced": int(y_ai.sum()), "expected": float(p_ai.sum()),
                          "unsafe": int(t["y"].sum()), "prevalence_unsafe": float(t["y"].mean())}
    for c in tests:
        res["harm"][c]["relative_to_standard"] = res["harm"][c]["attacker_induced"] / res["harm"]["standard"]["attacker_induced"]
    runs = {"mpnn__MPNN": mp}
    for m in MODELS[:-1]:
        runs[m] = train(m, dev, tests)
        print(f"{m} trained ({time.time() - t0:.0f}s)", flush=True)
    for m, rs in runs.items():
        res["models"][m] = {}
        for c, t in tests.items():
            ev = [evaluate(t, r["pred"][c], r["thr"]) for r in rs]
            agg = lambda lst: {k: [float(np.mean([e[k] for e in lst])), float(np.std([e[k] for e in lst], ddof=1)) if len(lst) > 1 else 0.0]
                               for k in lst[0]}
            res["models"][m][c] = agg(ev)
            if m == "mpnn__MPNN" and c == "blackbox":
                res["models"][m]["blackbox_queried_seed"] = agg(ev[:1])
                res["models"][m]["blackbox_other_seeds"] = agg(ev[1:])
    jdump(res, OD / "summary.json")
    print("harm", {c: (h["attacker_induced"], round(h["relative_to_standard"], 3)) for c, h in res["harm"].items()})
    for m, d in res["models"].items():
        for c, r in d.items():
            print(f"{m:16s} {c:22s} PRatk {r['pr_attacker'][0]:.3f} PRuns {r['pr_unsafe'][0]:.3f} "
                  f"rec@10 {r['recall_attacker_fpr10'][0]:.3f} rec@1 {r['recall_attacker_fpr1'][0]:.3f} "
                  f"fpr@10 {r['realised_fpr_fpr10'][0]:.3f}")
    print(f"done {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
